// 0x00E9C220: the scratchpad comes from the solver allocator (which may grant more than asked)
hkResult hkpDefaultToiResourceMgr::beginToiAndSetupResources(const hkpToiEvent& event, const hkArray<hkpToiEvent, hkContainerHeapAllocator>& otherEvents, hkpToiResources& resourcesOut)
{
    hkResult result;
    if (!shouldHandleGivenToi(event).m_bool)
    {
        result.m_enum = HK_FAILURE;
        return result;
    }
    resourcesOut.m_scratchpadSize = m_defaultScratchpadSize;
    m_scratchPadCapacity = m_defaultScratchpadSize;
    resourcesOut.m_scratchpad = (char*)hkMemoryRouter::getInstance().solver().bufAlloc(m_scratchPadCapacity);
    resourcesOut.m_maxNumActiveEntities = 1000;
    resourcesOut.m_maxNumConstraints = 1000;
    resourcesOut.m_maxNumEntities = 1000;
    resourcesOut.m_numToiSolverIterations = 3;
    resourcesOut.m_numForcedToiFinalSolverIterations = 4;
    resourcesOut.m_minPriorityToProcess = hkpConstraintInstance::PRIORITY_TOI;
    resourcesOut.m_priorityClassMap = s_priorityClassMap;
    resourcesOut.m_priorityClassRatios = s_priorityClassRatios;
    result.m_enum = HK_SUCCESS;
    return result;
}

// 0x00E9C2D0
void hkpDefaultToiResourceMgr::endToiAndFreeResources(const hkpToiEvent& event, const hkArray<hkpToiEvent, hkContainerHeapAllocator>& otherEvents, const hkpToiResources& resources)
{
    hkMemoryRouter::getInstance().solver().bufFree(resources.m_scratchpad, m_scratchPadCapacity);
}

