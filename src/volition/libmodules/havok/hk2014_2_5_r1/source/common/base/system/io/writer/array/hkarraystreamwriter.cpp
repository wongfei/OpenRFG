// 0x00CFF750
void hkArrayStreamWriter::clear()
{
    m_arr->setSizeUnchecked(0);
    m_offset = 0;
    nullTerminate();
}

// 0x00CFF7B0: overwrites from the offset, growing the array (and moving its 0) past the end
int hkArrayStreamWriter::write(const void* mem, int size)
{
    const int spaceLeft = m_arr->getSize() - m_offset;
    if (spaceLeft < size)
    {
        const int newSize = m_offset + size;
        m_arr->_reserve(m_allocator, newSize + 1);
        m_arr->setSizeUnchecked(newSize);
        m_arr->begin()[newSize] = 0;
    }
    else if (m_arr->getSize() < m_arr->getCapacity())
    {
        m_arr->begin()[m_arr->getSize()] = 0;
    }
    hkString::memCpy(m_arr->begin() + m_offset, mem, size);
    m_offset += size;
    return size;
}

// 0x00CFF960: before the start fails; past the end zero-fills up to the new end and its 0 (an unknown whence stays)
hkResult hkArrayStreamWriter::seek(int offset, hkStreamWriter::SeekWhence whence)
{
    int absOffset = offset;
    if (whence != STREAM_SET)
    {
        if (whence == STREAM_CUR)
        {
            absOffset = m_offset + offset;
        }
        else if (whence == STREAM_END)
        {
            absOffset = m_arr->getSize() - offset;
        }
        else
        {
            absOffset = m_offset;
        }
    }
    if (absOffset < 0)
    {
        return HK_FAILURE;
    }
    if (absOffset > m_arr->getSize())
    {
        const int withZero = absOffset + 1;
        m_arr->_reserve(m_allocator, withZero);
        const int added = withZero - m_arr->getSize();
        if (added > 0)
        {
            memset(m_arr->begin() + m_arr->getSize(), 0, added);
        }
        m_arr->setSizeUnchecked(absOffset);
    }
    m_offset = absOffset;
    return HK_SUCCESS;
}

// 0x00CE8D30
// Original bug kept: a taken array is freed as its 12-byte header only (delete through hkArrayBase<char>, whose
// destructor does nothing), so its data leaks.
hkArrayStreamWriter::~hkArrayStreamWriter()
{
    if (m_ownerShip == ARRAY_TAKE && m_arr != nullptr)
    {
        hkMemoryRouter::getInstance().heap().blockFree(m_arr, (int)sizeof(hkArrayBase<char>));
    }
}

