// 0x00FBEE60 (:32)
unsigned short hkUFloat8::getEncodedFloat(unsigned char index)
{
    return s_getEncodedFloat_encodedFloats[index];
}

// 0x00DF1200 (.h:91)
float hkUFloat8::decodeFloat(const unsigned short i)
{
    if (i == 0)
    {
        return 0.0f;
    }
    const unsigned int bits = ((unsigned int)i + DECODE_EXPONENT_BIAS) << ENCODE_MANTISSA_SHIFT;
    float f;
    memcpy(&f, &bits, sizeof(f));
    return f;
}

